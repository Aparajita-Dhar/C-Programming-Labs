#include <stdio.h> // Preprocessor directive to include standard input/output library

/* 
   Topic: Introduction to C Program Structure
   Note on Execution: 
   - C is a COMPILED language. A compiler reads this entire file at once and turns 
     it into a machine code file (.exe or a.out) before running it.
   - This is different from an INTERPRETER (like Python), which reads and executes 
     the code line-by-line during runtime.
*/

int main() { // Main function - the entry point of every C program
    
    // Printing a standard message to the console
    printf("Hello, World!\n");
    printf("C is a compiled language, making it highly efficient.\n");
    
    return 0; // Indicating that the program executed successfully
}
